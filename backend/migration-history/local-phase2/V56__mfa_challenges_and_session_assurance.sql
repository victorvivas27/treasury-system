-- Additive only: legacy factors are converted by the key-aware application initializer.
ALTER TABLE users ALTER COLUMN totp_secret TYPE TEXT;
ALTER TABLE user_tokens ADD COLUMN mfa_epoch BIGINT;

CREATE TABLE user_mfa_state (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    epoch BIGINT NOT NULL DEFAULT 0,
    last_totp_step BIGINT,
    failures INTEGER NOT NULL DEFAULT 0,
    blocked_until TIMESTAMP
);

CREATE TABLE mfa_challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    purpose VARCHAR(16) NOT NULL,
    epoch BIGINT NOT NULL,
    credential_hash VARCHAR(64) NOT NULL,
    secret_ciphertext TEXT,
    expires_at TIMESTAMP NOT NULL,
    consumed BOOLEAN NOT NULL DEFAULT FALSE,
    attempts INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX idx_mfa_challenges_user_expiry ON mfa_challenges(user_id, expires_at);

-- No pre-MFA session is allowed to become an MFA-authenticated session by rotation.
UPDATE user_tokens SET revoked_at = CURRENT_TIMESTAMP
WHERE type = 'REFRESH_TOKEN' AND revoked_at IS NULL
AND user_id IN (SELECT id FROM users WHERE totp_enabled = TRUE);
