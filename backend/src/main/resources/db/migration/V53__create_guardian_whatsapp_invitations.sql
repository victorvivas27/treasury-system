ALTER TABLE user_tokens ADD COLUMN invitation_channel VARCHAR(16);

CREATE TABLE guardian_whatsapp_invitations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
 guardian_id BIGINT NOT NULL REFERENCES apoderados(apoderado_id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 token_hash VARCHAR(64) NOT NULL,
 phone VARCHAR(16) NOT NULL,
 consent_source VARCHAR(200) NOT NULL,
 consent_at TIMESTAMP NOT NULL,
 consent_recorded_by BIGINT NOT NULL,
 created_at TIMESTAMP NOT NULL,
 expires_at TIMESTAMP NOT NULL,
 message_id VARCHAR(255) UNIQUE,
 delivery_status VARCHAR(30) NOT NULL,
 error_code VARCHAR(60),
 requested_at TIMESTAMP,
 accepted_at TIMESTAMP,
 delivered_at TIMESTAMP,
 simulated BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX idx_guardian_whatsapp_latest ON guardian_whatsapp_invitations (organization_id, guardian_id, id DESC);
