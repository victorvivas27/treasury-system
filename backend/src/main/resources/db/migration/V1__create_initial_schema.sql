CREATE TABLE alumnos
(
    alumno_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo     VARCHAR(15)  NOT NULL,
    nombre     VARCHAR(100) NOT NULL,
    curso      VARCHAR(50)  NOT NULL,
    created_at TIMESTAMP,
    updated_at TIMESTAMP,
    CONSTRAINT uk_alumnos_codigo UNIQUE (codigo)
);

CREATE TABLE apoderados
(
    apoderado_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo        VARCHAR(15)  NOT NULL,
    nombre        VARCHAR(50)  NOT NULL,
    email         VARCHAR(100) NOT NULL,
    telefono      VARCHAR(20)  NOT NULL,
    observaciones VARCHAR(500),
    created_at    TIMESTAMP,
    updated_at    TIMESTAMP,
    CONSTRAINT uk_apoderados_codigo UNIQUE (codigo),
    CONSTRAINT uk_apoderados_email UNIQUE (email)
);

CREATE TABLE familias
(
    familia_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alumno_id               BIGINT       NOT NULL,
    codigo                  VARCHAR(255) NOT NULL,
    observaciones_generales VARCHAR(200),
    created_at              TIMESTAMP,
    updated_at              TIMESTAMP,
    CONSTRAINT uk_familias_alumno UNIQUE (alumno_id)
);

CREATE TABLE familia_apoderados
(
    familia_id   BIGINT      NOT NULL,
    apoderado_id BIGINT      NOT NULL,
    parentesco   VARCHAR(50) NOT NULL,
    es_principal BOOLEAN     NOT NULL,
    CONSTRAINT uk_familia_apoderado UNIQUE (familia_id, apoderado_id),
    CONSTRAINT fk_familia_apoderados_familia
        FOREIGN KEY (familia_id) REFERENCES familias (familia_id)
);

CREATE TABLE users
(
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code               VARCHAR(20)  NOT NULL,
    nombre             VARCHAR(100) NOT NULL,
    correo             VARCHAR(100) NOT NULL,
    password           VARCHAR(100) NOT NULL,
    rol                VARCHAR(10)  NOT NULL,
    enabled            BOOLEAN      NOT NULL,
    account_non_locked BOOLEAN      NOT NULL,
    email_verified_at  TIMESTAMP,
    created_at         TIMESTAMP,
    updated_at         TIMESTAMP,
    CONSTRAINT uk_users_code UNIQUE (code),
    CONSTRAINT uk_users_correo UNIQUE (correo)
);

CREATE TABLE user_tokens
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    type       VARCHAR(30) NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP   NOT NULL,
    used_at    TIMESTAMP,
    created_at TIMESTAMP,
    CONSTRAINT uk_user_tokens_hash UNIQUE (token_hash),
    CONSTRAINT user_tokens_type_check
        CHECK (type IN ('EMAIL_VERIFICATION', 'PASSWORD_RESET', 'ACCOUNT_INVITATION')),
    CONSTRAINT fk_user_token_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE annual_fee_configs
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fee_year        INTEGER        NOT NULL,
    annual_amount   NUMERIC(14, 0) NOT NULL,
    allowed_mode    VARCHAR(20)    NOT NULL,
    annual_due_date DATE           NOT NULL,
    first_due_date  DATE           NOT NULL,
    second_due_date DATE           NOT NULL,
    created_at      TIMESTAMP      NOT NULL,
    updated_at      TIMESTAMP      NOT NULL,
    CONSTRAINT uk_annual_fee_year UNIQUE (fee_year)
);

CREATE TABLE family_fee_plans
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    config_id  BIGINT      NOT NULL,
    family_id  BIGINT      NOT NULL,
    mode       VARCHAR(20) NOT NULL,
    created_at TIMESTAMP   NOT NULL,
    updated_at TIMESTAMP   NOT NULL,
    CONSTRAINT uk_family_fee_plan UNIQUE (config_id, family_id),
    CONSTRAINT fk_fee_plan_config
        FOREIGN KEY (config_id) REFERENCES annual_fee_configs (id) ON DELETE CASCADE,
    CONSTRAINT fk_fee_plan_family
        FOREIGN KEY (family_id) REFERENCES familias (familia_id) ON DELETE CASCADE
);

CREATE TABLE fee_obligations
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id     BIGINT         NOT NULL,
    installment VARCHAR(20)    NOT NULL,
    concept     VARCHAR(80)    NOT NULL,
    amount      NUMERIC(14, 0) NOT NULL,
    due_date    DATE           NOT NULL,
    status      VARCHAR(20)    NOT NULL,
    created_at  TIMESTAMP      NOT NULL,
    updated_at  TIMESTAMP      NOT NULL,
    CONSTRAINT uk_fee_obligation UNIQUE (plan_id, installment),
    CONSTRAINT fk_fee_obligation_plan
        FOREIGN KEY (plan_id) REFERENCES family_fee_plans (id) ON DELETE CASCADE
);

CREATE TABLE fee_payments
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    obligation_id    BIGINT         NOT NULL,
    payment_date     DATE           NOT NULL,
    amount           NUMERIC(14, 0) NOT NULL,
    registered_by    VARCHAR(150)   NOT NULL,
    observations     VARCHAR(500),
    annulled         BOOLEAN        NOT NULL,
    annulled_at      TIMESTAMP,
    annulled_by      VARCHAR(150),
    annulment_reason VARCHAR(500),
