CREATE TABLE event_stands
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id          BIGINT         NOT NULL,
    name              VARCHAR(120)   NOT NULL,
    stand_date        DATE           NOT NULL,
    start_time        TIME           NOT NULL,
    end_time          TIME           NOT NULL,
    responsible       VARCHAR(150)   NOT NULL,
    initial_fund      NUMERIC(14, 2) NOT NULL,
    status            VARCHAR(20)    NOT NULL,
    debit_commission  NUMERIC(7, 4)  NOT NULL,
    credit_commission NUMERIC(7, 4)  NOT NULL,
    created_at        TIMESTAMP      NOT NULL,
    updated_at        TIMESTAMP      NOT NULL,
    version           BIGINT         NOT NULL,
    CONSTRAINT uk_event_stand_name UNIQUE (event_id, name),
    CONSTRAINT fk_event_stand_event
        FOREIGN KEY (event_id) REFERENCES school_events (id)
);

CREATE TABLE event_stand_payment_methods
(
    stand_id       BIGINT NOT NULL,
    payment_method VARCHAR(20),
    CONSTRAINT fk_stand_payment_method_stand
        FOREIGN KEY (stand_id) REFERENCES event_stands (id)
);

CREATE TABLE event_stand_products
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stand_id      BIGINT         NOT NULL,
    name          VARCHAR(120)   NOT NULL,
    category      VARCHAR(80),
    variant       VARCHAR(100),
    price         NUMERIC(14, 2) NOT NULL,
    initial_stock INTEGER,
    current_stock INTEGER,
    available     BOOLEAN        NOT NULL,
    created_at    TIMESTAMP      NOT NULL,
