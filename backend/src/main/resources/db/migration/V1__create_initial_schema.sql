CREATE TABLE school_events
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                   VARCHAR(150) NOT NULL,
    school_year            INTEGER      NOT NULL,
    event_date             DATE         NOT NULL,
    description            VARCHAR(1000),
    status                 VARCHAR(25)  NOT NULL,
    observations           VARCHAR(1000),
    gross_revenue          NUMERIC(14, 0),
    revenue_date           DATE,
    revenue_description    VARCHAR(250),
    revenue_payment_method VARCHAR(40),
    revenue_receipt        VARCHAR(100),
    revenue_notes          VARCHAR(500),
    settlement_remainder   NUMERIC(14, 0),
    settlement_confirmed   BOOLEAN      NOT NULL,
    created_at             TIMESTAMP    NOT NULL,
    updated_at             TIMESTAMP    NOT NULL,
