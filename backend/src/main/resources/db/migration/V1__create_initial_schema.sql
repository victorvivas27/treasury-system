CREATE TABLE event_stand_sale_items
(
    sale_id      BIGINT         NOT NULL,
    product_id   BIGINT         NOT NULL,
    product_name VARCHAR(120)   NOT NULL,
    category     VARCHAR(80),
    variant      VARCHAR(100),
