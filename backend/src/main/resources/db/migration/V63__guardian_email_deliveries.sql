CREATE TABLE guardian_email_deliveries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
 guardian_id BIGINT NOT NULL REFERENCES apoderados(apoderado_id) ON DELETE CASCADE,
 message_id VARCHAR(255) NOT NULL UNIQUE,
 status VARCHAR(30) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 event_at TIMESTAMP WITH TIME ZONE,
 version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_guardian_email_latest ON guardian_email_deliveries (organization_id, guardian_id, id DESC);
